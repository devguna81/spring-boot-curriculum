-- Oracle 21c 이상의 JSON 타입 컬럼. 저장할 때 JSON 문법을 검사하고 내부 이진 형식으로 보관한다.
CREATE TABLE products (
    id         NUMBER(19)    GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name       VARCHAR2(100) NOT NULL,
    attributes JSON          NOT NULL
);

-- 12c 이상에서도 쓸 수 있는 방식: CLOB에 IS JSON 제약을 건다. 내용은 문자열 그대로 보관된다.
CREATE TABLE products_clob (
    id         NUMBER(19)    GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name       VARCHAR2(100) NOT NULL,
    attributes CLOB          NOT NULL,
    CONSTRAINT ck_products_clob_json CHECK (attributes IS JSON)
);
