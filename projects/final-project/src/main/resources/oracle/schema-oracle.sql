-- schema-h2.sql과 같은 구조. meta만 Oracle JSON 타입이다(21c 이상).
CREATE TABLE fp_users (
    id            NUMBER(19)    GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username      VARCHAR2(30)  NOT NULL,
    password_hash VARCHAR2(100) NOT NULL,
    display_name  VARCHAR2(30)  NOT NULL,
    role          VARCHAR2(10)  NOT NULL,
    created_at    TIMESTAMP     DEFAULT CURRENT_TIMESTAMP NOT NULL,
    CONSTRAINT uk_fp_users_username UNIQUE (username),
    CONSTRAINT ck_fp_users_role CHECK (role IN ('USER', 'ADMIN'))
);

CREATE TABLE fp_posts (
    id         NUMBER(19)    GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    author_id  NUMBER(19)    NOT NULL,
    title      VARCHAR2(100) NOT NULL,
    content    CLOB          NOT NULL,
    pinned     NUMBER(1)     DEFAULT 0 NOT NULL,
    meta       JSON          NOT NULL,
    created_at TIMESTAMP     DEFAULT CURRENT_TIMESTAMP NOT NULL,
    CONSTRAINT fk_fp_posts_author FOREIGN KEY (author_id) REFERENCES fp_users (id)
);

CREATE INDEX ix_fp_posts_author ON fp_posts (author_id);
CREATE INDEX ix_fp_posts_created ON fp_posts (created_at);
