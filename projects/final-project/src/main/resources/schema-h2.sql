-- 사용자: 로그인 정보와 역할. 테이블 이름은 같은 Oracle 스키마를 쓰는 다른 챕터와 겹치지 않게 fp_ 접두사를 붙인다.
CREATE TABLE fp_users (
    id            BIGINT       GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username      VARCHAR(30)  NOT NULL,
    password_hash VARCHAR(100) NOT NULL,
    display_name  VARCHAR(30)  NOT NULL,
    role          VARCHAR(10)  NOT NULL,
    created_at    TIMESTAMP    DEFAULT CURRENT_TIMESTAMP NOT NULL,
    CONSTRAINT uk_fp_users_username UNIQUE (username),
    CONSTRAINT ck_fp_users_role CHECK (role IN ('USER', 'ADMIN'))
);

-- 게시글: 태그처럼 구조가 느슨한 값은 meta 컬럼에 JSON으로 둔다. 정렬에 쓰는 pinned는 JSON 안이 아니라 별도 컬럼이다.
-- H2는 JSON 타입에 문자열을 넣으면 따옴표로 감싸 저장하는 함정이 있어 CLOB을 쓴다(ch15).
CREATE TABLE fp_posts (
    id         BIGINT       GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    author_id  BIGINT       NOT NULL,
    title      VARCHAR(100) NOT NULL,
    content    CLOB         NOT NULL,
    pinned     BOOLEAN      DEFAULT FALSE NOT NULL,
    meta       CLOB         NOT NULL,
    created_at TIMESTAMP    DEFAULT CURRENT_TIMESTAMP NOT NULL,
    CONSTRAINT fk_fp_posts_author FOREIGN KEY (author_id) REFERENCES fp_users (id)
);

CREATE INDEX ix_fp_posts_author ON fp_posts (author_id);
CREATE INDEX ix_fp_posts_created ON fp_posts (created_at);
